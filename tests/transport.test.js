import test from 'node:test';
import assert from 'node:assert/strict';
import {youtubeRequest} from '../youtube.js';

test('session transport: fixed endpoint, account checks, max 500 and explicit failures', async () => {
  const config = {DATASYNC_ID:'fixture-account',LOGGED_IN:true,INNERTUBE_CONTEXT:{client:{clientName:'WEB',clientVersion:'test'}},SESSION_INDEX:0};
  globalThis.window = {ytcfg:{get:key=>config[key]}};
  globalThis.location = {origin:'https://www.youtube.com'};
  globalThis.document = {cookie:'SAPISID=not-a-real-session'};
  const originalFetch = globalThis.fetch;
  const sent = [];
  globalThis.fetch = async (url,options) => { sent.push({url,options}); return {ok:true,json:async()=>({status:'STATUS_SUCCEEDED'})}; };
  try {
    const identity = await youtubeRequest('identity');
    assert.equal(identity.ok,true); assert.equal(identity.account.length,64);
    assert.equal(sent.length,0);
    const ids = Array.from({length:500},(_,i)=>`entry-${i}`);
    const result = await youtubeRequest('remove',{account:identity.account,ids});
    assert.equal(result.ok,true);
    assert.equal(sent[0].url,'/youtubei/v1/browse/edit_playlist?prettyPrint=false');
    assert.equal(JSON.parse(sent[0].options.body).actions.length,500);
    assert.equal(JSON.parse(sent[0].options.body).playlistId,'WL');
    assert.match(sent[0].options.headers.Authorization,/^SAPISIDHASH /);
    assert.ok(!JSON.stringify(result).includes('not-a-real-session'));
    assert.equal((await youtubeRequest('remove',{account:identity.account,ids:[...ids,'extra']})).ok,false);
    assert.equal(sent.length,1);
    assert.equal((await youtubeRequest('remove',{account:'wrong-account',ids})).ok,false);
    assert.equal(sent.length,1);
    await youtubeRequest('browse',{account:identity.account});
    assert.equal(JSON.parse(sent[1].options.body).browseId,'VLWL');
    await youtubeRequest('browse',{account:identity.account,token:'page-two'});
    assert.equal(JSON.parse(sent[2].options.body).continuation,'page-two');
    const restored = await youtubeRequest('restore',{account:identity.account,ids:['video-to-restore']});
    assert.equal(restored.ok,true);
    assert.deepEqual(JSON.parse(sent[3].options.body).actions,[{addedVideoId:'video-to-restore',action:'ACTION_ADD_VIDEO'}]);
    const beforeEmptyPicker=sent.length;
    assert.equal((await youtubeRequest('playlists',{account:identity.account})).ok,false);
    assert.equal(sent.length,beforeEmptyPicker);
    await youtubeRequest('playlists',{account:identity.account,videoId:'sample'});
    assert.deepEqual(JSON.parse(sent.at(-1).options.body).videoIds,['sample']);
    assert.equal(sent.at(-1).url,'/youtubei/v1/playlist/get_add_to_playlist?prettyPrint=false');
    await youtubeRequest('create-playlist',{account:identity.account,title:'New'});
    assert.equal(JSON.parse(sent.at(-1).options.body).privacyStatus,'PRIVATE');
    await youtubeRequest('add-to-playlist',{account:identity.account,playlistId:'PL_TARGET',ids:['sample']});
    assert.equal(JSON.parse(sent.at(-1).options.body).playlistId,'PL_TARGET');
    assert.deepEqual(JSON.parse(sent.at(-1).options.body).actions,[{addedVideoId:'sample',action:'ACTION_ADD_VIDEO'}]);
    await youtubeRequest('delete-playlist',{account:identity.account,playlistId:'PL_DELETE'});
    assert.equal(sent.at(-1).url,'/youtubei/v1/playlist/delete?prettyPrint=false');
    assert.equal(JSON.parse(sent.at(-1).options.body).playlistId,'PL_DELETE');
    const beforeDeleteInvalid=sent.length;
    for(const playlistId of ['WL','LL','HL','RD123','',null,'PL/unsafe'])assert.equal((await youtubeRequest('delete-playlist',{account:identity.account,playlistId})).ok,false);
    assert.equal((await youtubeRequest('delete-playlist',{playlistId:'PL_DELETE'})).ok,false);
    assert.equal((await youtubeRequest('delete-playlist',{account:'other',playlistId:'PL_DELETE'})).ok,false);
    assert.equal(sent.length,beforeDeleteInvalid);
    const beforeInvalid=sent.length;
    assert.equal((await youtubeRequest('add-to-playlist',{account:identity.account,playlistId:'WL',ids:['sample']})).ok,false);
    assert.equal(sent.length,beforeInvalid);
    globalThis.fetch = async()=>({ok:false,status:429});
    assert.match((await youtubeRequest('browse',{account:identity.account})).error,/HTTP 429/);
  } finally { globalThis.fetch = originalFetch; }
});
